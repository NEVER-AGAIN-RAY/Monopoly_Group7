def evaluate(
    model: CandidateRanker,
    examples: Sequence[Example],
    device: torch.device,
) -> Dict[str, Any]:
    if not examples:
        return {"top1": 0.0, "mrr": 0.0, "decisions": 0, "candidates": 0}
    by_decision: Dict[str, List[Example]] = collections.defaultdict(list)
    for ex in examples:
        by_decision[ex.decision_id].append(ex)
    model.eval()
    correct = 0
    first_correct = 0
    random_expected_sum = 0.0
    reciprocal_sum = 0.0
    kind_totals: Dict[str, int] = collections.Counter()
    kind_correct: Dict[str, int] = collections.Counter()
    with torch.no_grad():
        for decision_id, group in by_decision.items():
            x = torch.from_numpy(np.stack([ex.features for ex in group])).float().to(device)
            scores = model(x).detach().cpu().numpy()
            order = list(np.argsort(-scores))
            labels = [ex.label for ex in group]
            chosen_index = labels.index(1)
            predicted_index = order[0]
            kind = group[0].decision_kind
            kind_totals[kind] += 1
            if predicted_index == chosen_index:
                correct += 1
                kind_correct[kind] += 1
            if chosen_index == 0:
                first_correct += 1
            random_expected_sum += 1.0 / max(1, len(group))
            rank = order.index(chosen_index) + 1
            reciprocal_sum += 1.0 / rank
    n = len(by_decision)
    by_kind = {
        kind: {
            "top1": kind_correct[kind] / total,
            "decisions": total,
        }
        for kind, total in sorted(kind_totals.items())
    }
    return {
        "top1": correct / n,
        "mrr": reciprocal_sum / n,
        "firstCandidateTop1": first_correct / n,
        "randomExpectedTop1": random_expected_sum / n,
        "decisions": n,
        "candidates": len(examples),
        "byKind": by_kind,
    }


def summarize_rows(rows: Sequence[Dict[str, Any]]) -> Dict[str, Any]:
    by_kind = collections.Counter(row["request"].get("decisionKind") for row in rows)
    by_source = collections.Counter(teacher_source(row) for row in rows)
    candidate_counts = [len(row["request"]["candidates"]) for row in rows]
    sessions = {row["request"].get("sessionId") for row in rows}
    return {
        "rows": len(rows),
        "sessions": len(sessions),
        "byKind": dict(sorted(by_kind.items())),
        "byTeacherSource": dict(sorted(by_source.items())),
        "avgCandidates": float(np.mean(candidate_counts)) if candidate_counts else 0.0,
        "maxCandidates": max(candidate_counts) if candidate_counts else 0,
    }


def teacher_source(row: Dict[str, Any]) -> str:
    return str(obj(obj(row.get("result")).get("metadata")).get("source", "unknown"))


def write_json(path: Path, obj_: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj_, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def obj(value: Any) -> Dict[str, Any]:
    return value if isinstance(value, dict) else {}


def list_obj(value: Any) -> List[Any]:
    return value if isinstance(value, list) else []


def string_list(value: Any) -> List[str]:
    if not isinstance(value, list):
        return []
    return [str(item) for item in value if item is not None and str(item)]


def parse_int_set(raw: str) -> set[int]:
    out: set[int] = set()
    for part in str(raw or "").split(","):
        text = part.strip()
        if not text:
            continue
        try:
            out.add(int(text))
        except ValueError:
            raise ValueError(f"invalid integer in comma-separated list: {text}") from None
    return out


def card_ids_from_list(cards: Sequence[Any]) -> List[str]:
    ids: List[str] = []
    for card in cards:
        if isinstance(card, dict) and card.get("id"):
            ids.append(str(card.get("id")))
    return ids


def card_ids_in_context(context: Dict[str, Any]) -> List[str]:
    ids: List[str] = []
    self_state = obj(context.get("self"))
    for key in ["handCards", "bankCards", "propertyZoneCards"]:
        ids.extend(card_ids_from_list(list_obj(self_state.get(key))))
    for player in list_obj(context.get("players")):
        if not isinstance(player, dict):
            continue
        for key in ["bankCards", "propertyZoneCards"]:
            ids.extend(card_ids_from_list(list_obj(player.get(key))))
    return ids


def card_ids_from_payload(payload: Dict[str, Any]) -> List[str]:
    ids: List[str] = []
    for key in ["cardId", "targetCardId", "actorCardId"]:
        value = payload.get(key)
        if value is not None and str(value):
            ids.append(str(value))
    ids.extend(string_list(payload.get("cardIds")))
    return ids


def number(value: Any) -> float:
    try:
        if value is None or value == "":
            return 0.0
        return float(value)
    except (TypeError, ValueError):
        return 0.0


def norm(value: Any, scale: float) -> float:
    if scale <= 0:
        return number(value)
    return max(-5.0, min(5.0, number(value) / scale))


def has(mapping: Dict[str, Any], key: str) -> float:
    value = mapping.get(key)
    return 0.0 if value is None or value == "" else 1.0


def add_one_hot(vec: List[float], value: str, vocab: Sequence[str]) -> None:
    value = (value or "").upper()
    for token in vocab:
        vec.append(1.0 if value == token else 0.0)
    vec.append(1.0 if value and value not in vocab else 0.0)


def find_card(context: Dict[str, Any], card_id: Any) -> Dict[str, Any]:
    if not card_id:
        return {}
    self_state = obj(context.get("self"))
    for key in ["handCards", "bankCards", "propertyZoneCards"]:
        for card in list_obj(self_state.get(key)):
            if isinstance(card, dict) and card.get("id") == card_id:
                return card
    for player in list_obj(context.get("players")):
        if not isinstance(player, dict):
            continue
        for key in ["bankCards", "propertyZoneCards", "handCards"]:
            for card in list_obj(player.get(key)):
                if isinstance(card, dict) and card.get("id") == card_id:
                    return card
    return {}


def candidate_index(candidate_id: Any) -> float:
    text = str(candidate_id or "")
    digits = "".join(ch for ch in text if ch.isdigit())
    return float(digits) if digits else 0.0


def number_after(text: str, marker: str) -> float:
    idx = text.find(marker)
    if idx < 0:
        return 0.0
    idx += len(marker)
    end = idx
    while end < len(text) and (text[end].isdigit() or text[end] in ".-"):
        end += 1
    try:
        return float(text[idx:end])
    except ValueError:
        return 0.0


def summary_hash_features(summary: str, bins: int) -> List[float]:
    values = [0.0] * bins
    for token in summary.upper().replace(",", " ").replace(".", " ").split():
        values[stable_token_bucket(token, bins)] += 1.0
    return [min(1.0, v / 3.0) for v in values]


def stable_token_bucket(token: str, bins: int) -> int:
    h = 2166136261
    for b in token.encode("utf-8"):
        h ^= b
        h = (h * 16777619) & 0xFFFFFFFF
    return h % bins


def main(argv: Sequence[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("inputs", nargs="+", type=Path)
    parser.add_argument("--output-dir", type=Path, default=Path("models/distillation/latest"))
    parser.add_argument("--mode", choices=["validate", "train"], default="train")
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--batch-size", type=int, default=256)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--model-type", choices=["mlp", "linear", "knn", "forest"], default="mlp")
    parser.add_argument("--knn-k", type=int, default=5)
    parser.add_argument("--forest-trees", type=int, default=16)
    parser.add_argument("--forest-features-per-tree", type=int, default=32)
    parser.add_argument(
        "--balance-by-kind",
        action="store_true",
        help="Upweight rare decision kinds with sqrt(max_count/kind_count).",
    )
    parser.add_argument("--kind-balance-max", type=float, default=4.0)
    parser.add_argument("--validation-ratio", type=float, default=0.2)
    parser.add_argument(
        "--split-by",
        choices=["session", "decision", "player-count"],
        default="session",
        help="Validation grouping. Session split avoids same-game leakage; player-count tests cross-player-count generalization.",
    )
    parser.add_argument(
        "--validation-player-counts",
        default="4,5",
        help="Comma-separated player counts used as validation when --split-by player-count.",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument(
        "--include-sources",
        default="",
        help="Comma-separated result.metadata.source allowlist, e.g. deepseek,first_choice. Empty means all.",
    )
    parser.add_argument("--min-rows", type=int, default=0)
    args = parser.parse_args(argv)

    include_sources = {
        item.strip()
        for item in args.include_sources.split(",")
        if item.strip()
    }
    rows, errors, skipped = load_rows(args.inputs, include_sources or None)
    summary = summarize_rows(rows)
    summary["skippedBySource"] = skipped
    if errors:
        report = {"ok": False, "errors": errors[:200], "errorCount": len(errors), "summary": summary}
        write_json(args.output_dir / "dataset_validation.json", report)
        print(json.dumps(report, ensure_ascii=False, indent=2), file=sys.stderr)
        return 1
    validation = {"ok": True, "errors": [], "summary": summary}
    if args.min_rows > 0 and summary["rows"] < args.min_rows:
        validation = {
            "ok": False,
            "errors": [f"rows {summary['rows']} below --min-rows {args.min_rows}"],
            "summary": summary,
        }
        write_json(args.output_dir / "dataset_validation.json", validation)
        print(json.dumps(validation, ensure_ascii=False, indent=2), file=sys.stderr)
        return 1
    write_json(args.output_dir / "dataset_validation.json", validation)
    print(json.dumps(validation, ensure_ascii=False, indent=2))
    if args.mode == "validate":
        return 0
    kind_weights = kind_balance_multipliers(
        rows,
        enabled=args.balance_by_kind,
        max_multiplier=args.kind_balance_max,
    )
    examples = build_examples_with_kind_balance(
        rows,
        enabled=args.balance_by_kind,
        max_multiplier=args.kind_balance_max,
    )
    validation_player_counts = parse_int_set(args.validation_player_counts)
    train_examples, val_examples = split_examples(
        examples,
        args.validation_ratio,
        args.seed,
        args.split_by,
        validation_player_counts,
    )
    started = time.time()
    if args.model_type == "knn":
        metrics = evaluate_knn_baseline(train_examples, val_examples, args.knn_k)
    elif args.model_type == "forest":
        metrics = evaluate_forest_baseline(
            train_examples,
            val_examples,
            args.forest_trees,
            args.forest_features_per_tree,
            args.seed,
        )
    else:
        metrics = train_model(
            train_examples,
            val_examples,
            args.output_dir,
            args.epochs,
            args.batch_size,
            args.lr,
            args.seed,
            args.model_type,
        )
    metrics.update(
        {
            "featureVersion": FEATURE_VERSION,
            "dataset": summary,
            "splitBy": args.split_by,
            "validationPlayerCounts": sorted(validation_player_counts)
            if args.split_by == "player-count"
            else [],
            "balanceByKind": bool(args.balance_by_kind),
            "kindBalanceMax": args.kind_balance_max,
            "kindWeights": kind_weights,
            "trainExamples": len(train_examples),
            "validationExamples": len(val_examples),
            "durationSeconds": round(time.time() - started, 3),
        }
    )
    write_json(args.output_dir / "metrics.json", metrics)
    print(json.dumps(metrics, ensure_ascii=False, indent=2))
    return 0


