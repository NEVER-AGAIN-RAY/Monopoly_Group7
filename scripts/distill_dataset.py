@dataclass(frozen=True)
class Example:
    features: np.ndarray
    label: int
    weight: float
    decision_kind: str
    session_id: str
    decision_id: str
    player_count: int


class CandidateDataset(Dataset):
    def __init__(self, examples: Sequence[Example]):
        self.examples = list(examples)

    def __len__(self) -> int:
        return len(self.examples)

    def __getitem__(self, idx: int) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
        ex = self.examples[idx]
        return (
            torch.from_numpy(ex.features).float(),
            torch.tensor(ex.label, dtype=torch.float32),
            torch.tensor(ex.weight, dtype=torch.float32),
        )


class CandidateRanker(nn.Module):
    def __init__(self, input_dim: int):
        super().__init__()
        hidden = int(max(32, min(256, input_dim * 2)))
        self.net = nn.Sequential(
            nn.Linear(input_dim, hidden),
            nn.ReLU(),
            nn.Dropout(0.05),
            nn.Linear(hidden, hidden // 2),
            nn.ReLU(),
            nn.Linear(hidden // 2, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x).squeeze(-1)


class LinearRanker(nn.Module):
    def __init__(self, input_dim: int):
        super().__init__()
        self.linear = nn.Linear(input_dim, 1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.linear(x).squeeze(-1)


def load_rows(
    paths: Sequence[Path],
    include_sources: set[str] | None,
) -> Tuple[List[Dict[str, Any]], List[str], Dict[str, int]]:
    rows: List[Dict[str, Any]] = []
    errors: List[str] = []
    skipped = collections.Counter()
    seen_decision_ids: set[str] = set()
    for path in paths:
        with path.open("r", encoding="utf-8") as handle:
            for line_no, line in enumerate(handle, start=1):
                raw = line.strip()
                if not raw:
                    continue
                try:
                    row = json.loads(raw)
                except json.JSONDecodeError as exc:
                    errors.append(f"{path}:{line_no}: invalid JSON: {exc}")
                    continue
                row_errors = validate_row(row)
                if row_errors:
                    errors.extend(f"{path}:{line_no}: {err}" for err in row_errors)
                    continue
                decision_id = row["request"]["decisionId"]
                if decision_id in seen_decision_ids:
                    errors.append(f"{path}:{line_no}: duplicate decisionId {decision_id}")
                    continue
                seen_decision_ids.add(decision_id)
                source = teacher_source(row)
                if include_sources is not None and source not in include_sources:
                    skipped[source] += 1
                    continue
                rows.append(row)
    return rows, errors, dict(sorted(skipped.items()))


def validate_row(row: Dict[str, Any]) -> List[str]:
    errors: List[str] = []
    if row.get("schema") != SCHEMA:
        errors.append(f"schema must be {SCHEMA}")
    request = row.get("request")
    result = row.get("result")
    if not isinstance(request, dict):
        return errors + ["request must be object"]
    if not isinstance(result, dict):
        return errors + ["result must be object"]
    required_request = [
        "decisionId",
        "sessionId",
        "actorPlayerId",
        "decisionKind",
        "context",
        "candidates",
    ]
    for key in required_request:
        if key not in request:
            errors.append(f"request.{key} is missing")
    candidates = request.get("candidates")
    if not isinstance(candidates, list) or not candidates:
        errors.append("request.candidates must be non-empty list")
        return errors
    candidate_ids = []
    for i, candidate in enumerate(candidates):
        if not isinstance(candidate, dict):
            errors.append(f"candidate[{i}] must be object")
            continue
        cid = candidate.get("id")
        if not isinstance(cid, str) or not cid:
            errors.append(f"candidate[{i}].id must be non-empty string")
        else:
            candidate_ids.append(cid)
        if "payload" not in candidate or not isinstance(candidate.get("payload"), dict):
            errors.append(f"candidate[{i}].payload must be object")
    if len(candidate_ids) != len(set(candidate_ids)):
        errors.append("candidate ids must be unique")
    if result.get("decisionId") != request.get("decisionId"):
        errors.append("result.decisionId must equal request.decisionId")
    if result.get("choiceId") not in set(candidate_ids):
        errors.append("result.choiceId must reference a legal candidate id")
    metadata = result.get("metadata")
    if metadata is not None and not isinstance(metadata, dict):
        errors.append("result.metadata must be object when present")
    context = request.get("context")
    if not isinstance(context, dict):
        errors.append("request.context must be object")
    else:
        errors.extend(validate_context(request, context))
    return errors


def validate_context(request: Dict[str, Any], context: Dict[str, Any]) -> List[str]:
    errors: List[str] = []
    game_meta = obj(context.get("gameMeta"))
    self_state = obj(context.get("self"))
    players = list_obj(context.get("players"))
    decision = obj(context.get("decision"))
    decision_kind = str(request.get("decisionKind", ""))
    candidate_ids = {
        str(candidate.get("id"))
        for candidate in list_obj(request.get("candidates"))
        if isinstance(candidate, dict) and candidate.get("id")
    }

    if game_meta:
        player_count = int(number(game_meta.get("playerCount")))
        if player_count and players and player_count != len(players):
            errors.append(f"context.gameMeta.playerCount {player_count} does not match players length {len(players)}")
        if str(game_meta.get("decisionKind", "")) != decision_kind:
            errors.append("context.gameMeta.decisionKind must equal request.decisionKind")
        if game_meta.get("decisionPlayerId") and request.get("actorPlayerId"):
            if str(game_meta.get("decisionPlayerId")) != str(request.get("actorPlayerId")):
                errors.append("context.gameMeta.decisionPlayerId must equal request.actorPlayerId")
        remaining = number(game_meta.get("actionsRemainingThisTurn"))
        if remaining < 0:
            errors.append("context.gameMeta.actionsRemainingThisTurn must be non-negative")
    elif decision_kind == "PLAY_CARD":
        errors.append("context.gameMeta is required for PLAY_CARD decisions")

    if self_state:
        if request.get("actorPlayerId") and self_state.get("id"):
            if str(self_state.get("id")) != str(request.get("actorPlayerId")):
                errors.append("context.self.id must equal request.actorPlayerId")
        if players:
            self_rows = [p for p in players if isinstance(p, dict) and bool(p.get("isSelf"))]
            if len(self_rows) != 1:
                errors.append("context.players must contain exactly one isSelf=true row")
            elif self_rows[0].get("id") != self_state.get("id"):
                errors.append("context.players self row must match context.self.id")
    else:
        errors.append("context.self is required")

    if decision:
        if str(decision.get("kind", "")) != decision_kind:
            errors.append("context.decision.kind must equal request.decisionKind")
        legal_ids = {
            str(candidate.get("id"))
            for candidate in list_obj(decision.get("legalCandidates"))
            if isinstance(candidate, dict) and candidate.get("id")
        }
        if legal_ids and legal_ids != candidate_ids:
            errors.append("context.decision.legalCandidates must match request.candidates ids")
    else:
        errors.append("context.decision is required")

    observed_card_ids = card_ids_in_context(context)
    duplicate_cards = sorted(card_id for card_id, count in collections.Counter(observed_card_ids).items() if count > 1)
    if duplicate_cards:
        errors.append("duplicate visible card ids in context: " + ",".join(duplicate_cards[:10]))

    for candidate in list_obj(request.get("candidates")):
        if not isinstance(candidate, dict):
            continue
        errors.extend(validate_candidate_payload(decision_kind, context, candidate))
    return errors


def validate_candidate_payload(
    decision_kind: str,
    context: Dict[str, Any],
    candidate: Dict[str, Any],
) -> List[str]:
    errors: List[str] = []
    payload = obj(candidate.get("payload"))
    candidate_id = str(candidate.get("id", "?"))
    self_state = obj(context.get("self"))
    hand_ids = set(card_ids_from_list(list_obj(self_state.get("handCards"))))
    payable_ids = {
        str(card.get("id"))
        for card in list_obj(obj(context.get("decision")).get("payableCards"))
        if isinstance(card, dict) and card.get("id")
    }
    discard_ids = {
        str(card.get("id"))
        for card in list_obj(obj(context.get("decision")).get("legalDiscardCards"))
        if isinstance(card, dict) and card.get("id")
    }
    visible_ids = set(card_ids_in_context(context))

    if decision_kind == "PLAY_CARD":
        card_id = payload.get("cardId")
        if card_id and str(card_id) not in hand_ids:
            errors.append(f"candidate {candidate_id} cardId {card_id} is not in self hand")
    elif decision_kind == "PAYMENT":
        ids = string_list(payload.get("cardIds"))
        if not ids:
            errors.append(f"candidate {candidate_id} payment cardIds must be non-empty")
        missing = sorted(set(ids) - payable_ids) if payable_ids else sorted(set(ids) - visible_ids)
        if missing:
            errors.append(f"candidate {candidate_id} payment cardIds not payable: {','.join(missing[:10])}")
        amount = number(payload.get("amountPaidM"))
        if amount <= 0:
            errors.append(f"candidate {candidate_id} amountPaidM must be positive")
    elif decision_kind == "OVERFLOW_DISCARD":
        ids = string_list(payload.get("cardIds"))
        need = int(number(obj(context.get("decision")).get("discardCount")))
        if need and len(ids) != need:
            errors.append(f"candidate {candidate_id} discard card count {len(ids)} does not match discardCount {need}")
        missing = sorted(set(ids) - (discard_ids or hand_ids))
        if missing:
            errors.append(f"candidate {candidate_id} discard cardIds not in hand: {','.join(missing[:10])}")
    elif decision_kind == "JUST_SAY_NO":
        if candidate_id == "PLAY_JSN":
            if payload and visible_ids:
                jsn_ids = {
                    card_id
                    for card_id in card_ids_from_payload(payload)
                    if "say" in card_id.lower() or "waiver" in card_id.lower() or "ACT_" in card_id
                }
                if jsn_ids and not (jsn_ids & hand_ids):
                    errors.append(f"candidate {candidate_id} Just Say No card is not in self hand")
    return errors


def build_examples(rows: Sequence[Dict[str, Any]]) -> List[Example]:
    return build_examples_with_kind_balance(rows, enabled=False, max_multiplier=1.0)


def build_examples_with_kind_balance(
    rows: Sequence[Dict[str, Any]],
    enabled: bool,
    max_multiplier: float,
) -> List[Example]:
    examples: List[Example] = []
    kind_multipliers = kind_balance_multipliers(rows, enabled, max_multiplier)
    for row in rows:
        request = row["request"]
        result = row["result"]
        context = request.get("context", {})
        candidates = request["candidates"]
        choice_id = result["choiceId"]
        decision_kind = str(request.get("decisionKind", ""))
        player_count = int(number(obj(context.get("gameMeta")).get("playerCount")))
        class_weight = max(1.0, (len(candidates) - 1) / 2.0)
        kind_weight = kind_multipliers.get(decision_kind, 1.0)
        for candidate in candidates:
            label = 1 if candidate["id"] == choice_id else 0
            weight = (class_weight if label else 1.0) * kind_weight
            examples.append(
                Example(
                    features=features_for(request, context, candidate),
                    label=label,
                    weight=weight,
                    decision_kind=decision_kind,
                    session_id=str(request.get("sessionId", "")),
                    decision_id=str(request.get("decisionId", "")),
                    player_count=player_count,
                )
            )
    return examples


def kind_balance_multipliers(
    rows: Sequence[Dict[str, Any]],
    enabled: bool,
    max_multiplier: float,
) -> Dict[str, float]:
    counts = collections.Counter(str(row["request"].get("decisionKind", "")) for row in rows)
    if not enabled or not counts:
        return {kind: 1.0 for kind in counts}
    max_count = max(counts.values())
    cap = max(1.0, float(max_multiplier))
    multipliers = {}
    for kind, count in counts.items():
        raw = math.sqrt(max_count / max(1, count))
        multipliers[kind] = round(min(cap, max(1.0, raw)), 6)
    return dict(sorted(multipliers.items()))


def features_for(
    request: Dict[str, Any],
    context: Dict[str, Any],
    candidate: Dict[str, Any],
) -> np.ndarray:
    vec: List[float] = []
    decision_kind = str(request.get("decisionKind", ""))
    game_meta = obj(context.get("gameMeta"))
    self_state = obj(context.get("self"))
    players = list_obj(context.get("players"))
    decision = obj(context.get("decision"))
    payload = obj(candidate.get("payload"))
    summary = str(candidate.get("summary", ""))

    add_one_hot(vec, decision_kind, DECISION_KINDS)
    vec.extend(
        [
            norm(game_meta.get("playerCount"), 5),
            norm(game_meta.get("roundNumber"), 30),
            norm(game_meta.get("actionsUsedThisTurn"), 3),
            norm(game_meta.get("actionsRemainingThisTurn"), 3),
            norm(self_state.get("bankM"), 30),
            norm(self_state.get("propertyPayM"), 40),
            norm(self_state.get("completeSets"), 3),
            norm(self_state.get("handCount"), 15),
            norm(len(players), 5),
            norm(len(list_obj(context.get("effectStack"))), 8),
            norm(request.get("stateSequence"), 500),
            norm(len(list_obj(decision.get("legalCandidates"))), 40),
            norm(candidate_index(candidate.get("id")), 40),
        ]
    )

    opponents = [p for p in players if not bool(p.get("isSelf"))]
    max_opp_sets = max([number(p.get("completeSets")) for p in opponents] or [0.0])
    max_opp_bank = max([number(p.get("bankM")) for p in opponents] or [0.0])
    max_opp_prop = max([number(p.get("propertyPayM")) for p in opponents] or [0.0])
    vec.extend([norm(max_opp_sets, 3), norm(max_opp_bank, 30), norm(max_opp_prop, 40)])

    add_one_hot(vec, str(payload.get("actionType", "")), ACTION_TYPES)
    add_one_hot(vec, str(payload.get("targetColorKey", "")), COLORS)
    add_one_hot(vec, str(payload.get("effectCode", "")), EFFECT_CODES)

    card = find_card(context, payload.get("cardId"))
    add_one_hot(vec, str(card.get("kind", "")), CARD_KINDS)
    add_one_hot(vec, str(card.get("effectCode", "")), EFFECT_CODES)
    add_one_hot(vec, str(card.get("color", card.get("colorGroup", ""))), COLORS)
    vec.extend(
        [
            norm(card.get("valueM"), 10),
            norm(obj(payload).get("amountPaidM"), 20),
            norm(len(list_obj(payload.get("cardIds"))), 10),
            has(payload, "targetPlayerId"),
            has(payload, "targetCardId"),
            has(payload, "actorCardId"),
        ]
    )

    summary_upper = summary.upper()
    for token in SUMMARY_TOKENS:
        vec.append(1.0 if token in summary_upper else 0.0)
    for marker in [
        "completionScore=",
        "expectedPaid=",
        "netScore=",
        "Pay ",
        "BANK ",
    ]:
        vec.append(norm(number_after(summary, marker), 100))

    vec.extend(summary_hash_features(summary, 16))
    return np.asarray(vec, dtype=np.float32)


def split_examples(
    examples: Sequence[Example],
    validation_ratio: float,
    seed: int,
    split_by: str,
    validation_player_counts: set[int] | None = None,
) -> Tuple[List[Example], List[Example]]:
    if split_by == "player-count":
        counts = validation_player_counts or {4, 5}
        train = [ex for ex in examples if ex.player_count not in counts]
        val = [ex for ex in examples if ex.player_count in counts]
        if train and val:
            return train, val
        raise ValueError(
            "player-count split requires examples on both sides; "
            f"validation counts={sorted(counts)}, observed={sorted({ex.player_count for ex in examples})}"
        )
    by_group: Dict[str, List[Example]] = collections.defaultdict(list)
    for ex in examples:
        key = ex.session_id if split_by == "session" else ex.decision_id
        by_group[key].append(ex)
    keys = list(by_group)
    rng = random.Random(seed)
    rng.shuffle(keys)
    val_count = max(1, int(round(len(keys) * validation_ratio))) if len(keys) > 1 else 0
    val_keys = set(keys[:val_count])
    train: List[Example] = []
    val: List[Example] = []
    for key, group in by_group.items():
        (val if key in val_keys else train).extend(group)
    return train, val


def train_model(
    train_examples: Sequence[Example],
    val_examples: Sequence[Example],
    output_dir: Path,
    epochs: int,
    batch_size: int,
    lr: float,
    seed: int,
    model_type: str,
) -> Dict[str, Any]:
    if not train_examples:
        raise ValueError("no training examples")
    input_dim = int(train_examples[0].features.shape[0])
    torch.manual_seed(seed)
    np.random.seed(seed)
    random.seed(seed)
    device = torch.device("mps" if torch.backends.mps.is_available() else "cpu")
    model = (LinearRanker(input_dim) if model_type == "linear" else CandidateRanker(input_dim)).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=lr, weight_decay=1e-4)
    criterion = nn.BCEWithLogitsLoss(reduction="none")
    loader = DataLoader(
        CandidateDataset(train_examples),
        batch_size=max(1, batch_size),
        shuffle=True,
    )

    best_state = None
    best_val_acc = -1.0
    history: List[Dict[str, float]] = []
    for epoch in range(1, epochs + 1):
        model.train()
        losses = []
        for x, y, w in loader:
            x = x.to(device)
            y = y.to(device)
            w = w.to(device)
            optimizer.zero_grad(set_to_none=True)
            logits = model(x)
            loss = (criterion(logits, y) * w).mean()
            loss.backward()
            optimizer.step()
            losses.append(float(loss.detach().cpu()))
        train_metrics = evaluate(model, train_examples, device)
        val_metrics = evaluate(model, val_examples, device) if val_examples else {}
        row = {
            "epoch": epoch,
            "loss": float(np.mean(losses)) if losses else 0.0,
            "train_top1": train_metrics.get("top1", 0.0),
            "train_mrr": train_metrics.get("mrr", 0.0),
            "val_top1": val_metrics.get("top1", 0.0),
            "val_mrr": val_metrics.get("mrr", 0.0),
        }
        history.append(row)
        if not val_examples or row["val_top1"] >= best_val_acc:
            best_val_acc = row["val_top1"]
            best_state = {k: v.detach().cpu() for k, v in model.state_dict().items()}
    if best_state is not None:
        model.load_state_dict(best_state)

    output_dir.mkdir(parents=True, exist_ok=True)
    model_path = output_dir / "candidate_ranker.pt"
    torch.save(
        {
            "state_dict": model.state_dict(),
            "input_dim": input_dim,
            "feature_version": FEATURE_VERSION,
            "decision_kinds": DECISION_KINDS,
            "action_types": ACTION_TYPES,
            "effect_codes": EFFECT_CODES,
            "colors": COLORS,
            "card_kinds": CARD_KINDS,
            "model_type": model_type,
        },
        model_path,
    )
    if model_type == "linear":
        json_model_path = output_dir / "candidate_ranker_linear.json"
        export_linear_json(model, json_model_path, input_dim)
    else:
        json_model_path = output_dir / "candidate_ranker_mlp.json"
        export_mlp_json(model, json_model_path, input_dim)
    final_train = evaluate(model, train_examples, device)
    final_val = evaluate(model, val_examples, device) if val_examples else {}
    return {
        "modelPath": str(model_path),
        "jsonModelPath": str(json_model_path) if json_model_path else None,
        "modelType": model_type,
        "device": str(device),
        "inputDim": input_dim,
        "epochs": epochs,
        "history": history,
        "train": final_train,
        "validation": final_val,
    }


def evaluate_knn_baseline(
    train_examples: Sequence[Example],
    val_examples: Sequence[Example],
    k: int,
) -> Dict[str, Any]:
    if not train_examples:
        raise ValueError("no training examples")
    k = max(1, k)
    positives = [ex for ex in train_examples if ex.label == 1]
    reference = positives if positives else list(train_examples)
    ref_features = np.nan_to_num(
        np.stack([ex.features for ex in reference]).astype(np.float64),
        nan=0.0,
        posinf=5.0,
        neginf=-5.0,
    )
    ref_norm = np.zeros(ref_features.shape[0], dtype=np.float64)
    return {
        "modelType": "knn",
        "k": k,
        "referenceExamples": len(reference),
        "referencePositiveOnly": bool(positives),
        "train": evaluate_knn(reference, ref_features, ref_norm, train_examples, k),
        "validation": evaluate_knn(reference, ref_features, ref_norm, val_examples, k),
    }


def evaluate_knn(
    reference: Sequence[Example],
    ref_features: np.ndarray,
    ref_norm: np.ndarray,
    examples: Sequence[Example],
    k: int,
) -> Dict[str, Any]:
    if not examples:
        return {"top1": 0.0, "mrr": 0.0, "decisions": 0, "candidates": 0}
    by_decision: Dict[str, List[Example]] = collections.defaultdict(list)
    for ex in examples:
        by_decision[ex.decision_id].append(ex)
    correct = 0
    first_correct = 0
    random_expected_sum = 0.0
    reciprocal_sum = 0.0
    kind_totals: Dict[str, int] = collections.Counter()
    kind_correct: Dict[str, int] = collections.Counter()
    for group in by_decision.values():
        scores = [knn_score(ex.features, ref_features, ref_norm, k) for ex in group]
        order = list(np.argsort(-np.asarray(scores)))
        labels = [ex.label for ex in group]
        chosen_index = labels.index(1)
        predicted_index = order[0]
        kind = group[0].decision_kind
        kind_totals[kind] += 1
        if predicted_index == chosen_index:
            correct += 1
            kind_correct[kind] += 1
        if chosen_index == 0:
            first_correct += 1
        random_expected_sum += 1.0 / max(1, len(group))
        reciprocal_sum += 1.0 / (order.index(chosen_index) + 1)
    n = len(by_decision)
    by_kind = {
        kind: {
            "top1": kind_correct[kind] / total,
            "decisions": total,
        }
        for kind, total in sorted(kind_totals.items())
    }
    return {
        "top1": correct / n,
        "mrr": reciprocal_sum / n,
        "firstCandidateTop1": first_correct / n,
        "randomExpectedTop1": random_expected_sum / n,
        "decisions": n,
        "candidates": len(examples),
        "byKind": by_kind,
    }


def knn_score(features: np.ndarray, ref_features: np.ndarray, ref_norm: np.ndarray, k: int) -> float:
    clean_features = np.nan_to_num(
        features.astype(np.float64),
        nan=0.0,
        posinf=5.0,
        neginf=-5.0,
    )
    del ref_norm
    diff = ref_features - clean_features
    distances = np.sqrt(np.sum(diff * diff, axis=1))
    if distances.size <= k:
        return -float(np.mean(distances))
    nearest = np.partition(distances, k - 1)[:k]
    return -float(np.mean(nearest))


def evaluate_forest_baseline(
    train_examples: Sequence[Example],
    val_examples: Sequence[Example],
    trees: int,
    features_per_tree: int,
    seed: int,
) -> Dict[str, Any]:
    if not train_examples:
        raise ValueError("no training examples")
    input_dim = int(train_examples[0].features.shape[0])
    rng = random.Random(seed)
    trees = max(1, trees)
    features_per_tree = max(1, min(input_dim, features_per_tree))
    ensemble = []
    for index in range(trees):
        feature_ids = sorted(rng.sample(range(input_dim), features_per_tree))
        weights, bias = fit_linear_numpy(
            bootstrap_examples(train_examples, rng),
            feature_ids,
            lr=0.015,
            epochs=24,
        )
        ensemble.append({"featureIds": feature_ids, "weights": weights, "bias": bias})
    return {
        "modelType": "forest",
        "trees": trees,
        "featuresPerTree": features_per_tree,
        "train": evaluate_forest(ensemble, train_examples),
        "validation": evaluate_forest(ensemble, val_examples),
    }


def bootstrap_examples(examples: Sequence[Example], rng: random.Random) -> List[Example]:
    if not examples:
        return []
    return [examples[rng.randrange(len(examples))] for _ in range(len(examples))]


def fit_linear_numpy(
    examples: Sequence[Example],
    feature_ids: Sequence[int],
    lr: float,
    epochs: int,
) -> Tuple[List[float], float]:
    x = np.nan_to_num(
        np.stack([ex.features[list(feature_ids)] for ex in examples]).astype(np.float64),
        nan=0.0,
        posinf=5.0,
        neginf=-5.0,
    )
    y = np.asarray([ex.label for ex in examples], dtype=np.float64)
    w = np.asarray([ex.weight for ex in examples], dtype=np.float64)
    w = np.nan_to_num(w, nan=1.0, posinf=1.0, neginf=1.0)
    mean_weight = float(np.mean(w)) if len(w) else 1.0
    if mean_weight > 0:
        w = w / mean_weight
    weights = np.zeros(x.shape[1], dtype=np.float64)
    bias = 0.0
    scale = max(1.0, float(len(examples)))
    for _ in range(max(1, epochs)):
        with np.errstate(over="ignore", divide="ignore", invalid="ignore"):
            raw_logits = x @ weights + bias
        logits = np.clip(np.nan_to_num(raw_logits, nan=0.0, posinf=30.0, neginf=-30.0), -30.0, 30.0)
        probs = 1.0 / (1.0 + np.exp(-logits))
        err = (probs - y) * w
        with np.errstate(over="ignore", divide="ignore", invalid="ignore"):
            raw_grad_w = (x.T @ err) / scale + 1e-4 * weights
        grad_w = raw_grad_w
        grad_b = float(np.nan_to_num(np.sum(err) / scale, nan=0.0, posinf=5.0, neginf=-5.0))
        grad_w = np.clip(np.nan_to_num(grad_w, nan=0.0, posinf=5.0, neginf=-5.0), -5.0, 5.0)
        grad_b = max(-5.0, min(5.0, grad_b))
        weights -= lr * grad_w
        weights = np.nan_to_num(np.clip(weights, -20.0, 20.0), nan=0.0, posinf=20.0, neginf=-20.0)
        bias -= lr * grad_b
        bias = float(np.nan_to_num(bias, nan=0.0, posinf=20.0, neginf=-20.0))
    return weights.astype(float).tolist(), float(bias)


def evaluate_forest(
    ensemble: Sequence[Dict[str, Any]],
    examples: Sequence[Example],
) -> Dict[str, Any]:
    return evaluate_scored_examples(examples, lambda ex: forest_score(ensemble, ex.features))


def forest_score(ensemble: Sequence[Dict[str, Any]], features: np.ndarray) -> float:
    if not ensemble:
        return 0.0
    total = 0.0
    for tree in ensemble:
        feature_ids = tree["featureIds"]
        weights = np.asarray(tree["weights"], dtype=np.float64)
        total += float(np.asarray(features[feature_ids], dtype=np.float64) @ weights + tree["bias"])
    return total / len(ensemble)


def evaluate_scored_examples(
    examples: Sequence[Example],
    score_fn,
) -> Dict[str, Any]:
    if not examples:
        return {"top1": 0.0, "mrr": 0.0, "decisions": 0, "candidates": 0}
    by_decision: Dict[str, List[Example]] = collections.defaultdict(list)
    for ex in examples:
        by_decision[ex.decision_id].append(ex)
    correct = 0
    first_correct = 0
    random_expected_sum = 0.0
    reciprocal_sum = 0.0
    kind_totals: Dict[str, int] = collections.Counter()
    kind_correct: Dict[str, int] = collections.Counter()
    for group in by_decision.values():
        scores = [score_fn(ex) for ex in group]
        order = list(np.argsort(-np.asarray(scores)))
        labels = [ex.label for ex in group]
        chosen_index = labels.index(1)
        predicted_index = order[0]
        kind = group[0].decision_kind
        kind_totals[kind] += 1
        if predicted_index == chosen_index:
            correct += 1
            kind_correct[kind] += 1
        if chosen_index == 0:
            first_correct += 1
        random_expected_sum += 1.0 / max(1, len(group))
        reciprocal_sum += 1.0 / (order.index(chosen_index) + 1)
    n = len(by_decision)
    by_kind = {
        kind: {
            "top1": kind_correct[kind] / total,
            "decisions": total,
        }
        for kind, total in sorted(kind_totals.items())
    }
    return {
        "top1": correct / n,
        "mrr": reciprocal_sum / n,
        "firstCandidateTop1": first_correct / n,
        "randomExpectedTop1": random_expected_sum / n,
        "decisions": n,
        "candidates": len(examples),
        "byKind": by_kind,
    }


